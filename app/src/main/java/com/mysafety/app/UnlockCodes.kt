    private fun sp(c: Context) =
        c.applicationContext.getSharedPreferences("my_safety_unlock", Context.MODE_PRIVATE)

    fun slotOf(timeMs: Long): Int {
        val cal = Calendar.getInstance(ZONE)
        cal.timeInMillis = timeMs
        val minutes = cal.get(Calendar.HOUR_OF_DAY) * 60 + cal.get(Calendar.MINUTE)
        return minutes / SLOT_MINUTES
    }

    private fun fmt(totalMin: Int): String {
        val h24 = (totalMin / 60) % 24
        val m = totalMin % 60
        val h12 = if (h24 % 12 == 0) 12 else h24 % 12
        return String.format(Locale.US, "%02d:%02d %s", h12, m, if (h24 < 12) "AM" else "PM")
    }

    fun label(slot: Int): String =
        fmt(slot * SLOT_MINUTES) + " – " + fmt((slot * SLOT_MINUTES + SLOT_MINUTES) % (24 * 60))

    fun currentLabel(): String = label(slotOf(System.currentTimeMillis()))

    fun cooldownLeftMs(c: Context): Long {
        val until = sp(c).getLong("until", 0L)
        return min(COOLDOWN_MS, max(0L, until - System.currentTimeMillis()))
    }

    fun failsLeft(c: Context): Int = MAX_FAILS - sp(c).getInt("fails", 0)

    @Synchronized
    fun verify(c: Context, input: String): Result {
        if (cooldownLeftMs(c) > 0) return Result.COOLDOWN
        if (LockStore.clockChanged(c, DRIFT_TOLERANCE_MS)) return Result.CLOCK_CHANGED

        val now = System.currentTimeMillis()
        val slot = slotOf(now)
        val entered = input.trim()
        var ok = false
        for (i in 0..GRACE_SLOTS) {
            if (CODES[(slot - i + SLOT_COUNT) % SLOT_COUNT] == entered) ok = true
        }

        val p = sp(c)
        if (ok) { p.edit().clear().apply(); return Result.OK }

        val fails = p.getInt("fails", 0) + 1
        if (fails >= MAX_FAILS) {
            p.edit().putInt("fails", 0).putLong("until", now + COOLDOWN_MS).apply()
            return Result.COOLDOWN
        }
        p.edit().putInt("fails", fails).apply()
        return Result.WRONG
    }
